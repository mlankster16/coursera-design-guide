/* Export the built site as a flat folder of named, standalone HTML files.
 *
 * The site itself has to keep its pages nested as <route>/index.html, which
 * leaves a folder full of files all called index.html. This writes the same
 * pages to live-pages/ under their own names, with styles, scripts and the
 * logo inlined, so each file opens by double-click and can be sent on its own.
 *
 * Runs at the end of `npm run build`, reading dist/. live-pages/ is generated
 * and untracked: never edit it, it is replaced on every build.
 */
import fs from 'node:fs';
import path from 'node:path';

const DIST = 'dist';
const OUT = 'live-pages';
const BASE = '/coursera-design-guide';
const HELD = 'not-yet-released';

/** Route (no leading or trailing slash) -> exported file. Pages under HELD are
 *  built and exported here, then removed from dist/ so they are not deployed. */
const PAGES = {
  '': 'start-here.html',
  'specialization': 'specialization.html',
  'course': 'course.html',
  'module': 'module.html',
  'learning-assets': 'learning-assets.html',
  'learning-assets/accessibility-copyright-ai': 'accessibility-copyright-ai.html',
  'learning-assets/video': `${HELD}/video.html`,
  'learning-assets/reading': `${HELD}/reading.html`,
};
/** Routes that only redirect: links to them go to the redirect's target. */
const ALIASES = { orient: '' };

if (!fs.existsSync(DIST)) throw new Error(`${DIST}/ not found: run astro build first`);

const routeOf = (url) => url.slice(BASE.length).replace(/^\/+|\/+$/g, '');
const distFile = (url) => path.join(DIST, url.slice(BASE.length));
const isAsset = (url) => {
  const f = distFile(url);
  return path.extname(f) !== '' && fs.existsSync(f) && fs.statSync(f).isFile();
};
const read = (url) => fs.readFileSync(distFile(url), 'utf8');

function exportPage(route, outRel) {
  const src = path.join(DIST, route, 'index.html');
  if (!fs.existsSync(src)) throw new Error(`expected page missing from build: ${src}`);
  let html = fs.readFileSync(src, 'utf8');
  const up = path.relative(path.dirname(outRel), '.') || '.';

  // Stylesheets and scripts become inline blocks.
  html = html.replace(/<link\b[^>]*>/g, (tag) => {
    const href = tag.match(/\bhref="([^"]+)"/)?.[1];
    if (!/\brel="stylesheet"/.test(tag) || !href?.startsWith(BASE) || !isAsset(href)) return tag;
    return `<style>\n${read(href)}\n</style>`;
  });
  html = html.replace(/<script\b([^>]*)\bsrc="([^"]+)"([^>]*)><\/script>/g, (tag, a, srcUrl, b) => {
    if (!srcUrl.startsWith(BASE) || !isAsset(srcUrl)) return tag;
    return `<script${a}${b}>\n${read(srcUrl).replace(/<\/script/gi, '<\\/script')}\n</script>`;
  });

  // Remaining site URLs: pages become relative links, images become data URIs.
  html = html.replace(/\b(href|src)="(\/coursera-design-guide(?:[/#?][^"]*)?)"/g, (m, attr, url) => {
    const [pathPart, hash = ''] = url.split(/(?=#)/);
    if (isAsset(pathPart)) {
      const ext = path.extname(pathPart).slice(1).toLowerCase();
      const mime = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', svg: 'image/svg+xml', gif: 'image/gif', webp: 'image/webp' }[ext];
      if (!mime) throw new Error(`${src}: no way to inline ${url}`);
      return `${attr}="data:${mime};base64,${fs.readFileSync(distFile(pathPart)).toString('base64')}"`;
    }
    let r = routeOf(pathPart);
    if (r in ALIASES) r = ALIASES[r];
    if (!(r in PAGES)) throw new Error(`${src}: link to a route that is not exported: ${url}`);
    return `${attr}="${up}/${PAGES[r]}${hash}"`;
  });

  const live = `https://mlankster16.github.io${BASE}/${route}`;
  html = html.replace(/<!doctype html>/i, (d) =>
    `${d}\n<!-- Exported copy of ${live} — generated by npm run build. Do not edit: see README.md, "Changing these pages". -->`);

  const dest = path.join(OUT, outRel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, html);
}

fs.rmSync(OUT, { recursive: true, force: true });
for (const [route, outRel] of Object.entries(PAGES)) exportPage(route, outRel);

fs.writeFileSync(path.join(OUT, 'README.txt'), `Live pages of the Coursera Design Guide, one standalone file each.

These match what is published at https://mlankster16.github.io${BASE}
as of the last "npm run build". Each file opens by double-click and can be
sent or uploaded on its own (fonts load from Google Fonts, so they need a
connection to look right).

${HELD}/ holds the asset guides that are built but not yet released. They
are not on the published site: the build removes them before deploying, and
the Learning Assets page shows "Guide available soon" for them.

This folder is generated. Do not edit these files: changes are overwritten on
the next build. To change a page, see README.md in the project root.
`);

// Held pages are kept out of the published site: remove them from dist/ now
// that their standalone copies exist. To release one, move its PAGES entry
// out of HELD (and add its slug to "released" on the Learning Assets page).
const held = Object.entries(PAGES).filter(([, out]) => out.startsWith(`${HELD}/`)).map(([route]) => route);
for (const route of held) fs.rmSync(path.join(DIST, route), { recursive: true, force: true });
console.log(`dist/: withheld ${held.map((r) => `/${r}`).join(', ')}`);

console.log(`live-pages/: exported ${Object.keys(PAGES).length} pages`);
